export type Locale = keyof typeof copy;
export type CopyKey = keyof (typeof copy)["en"];

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (k: CopyKey) => string };

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("syntect.locale");
    if (saved === "en" || saved === "tr") setLocaleState(saved);
  }, []);
  const setLocale = (l: Locale) => {
    setLocaleState(l);
    window.localStorage.setItem("syntect.locale", l);
  };
  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      t: (k) => copy[locale][k],
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("i18n");
  return ctx;
}
